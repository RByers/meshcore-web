/** Sets `description` on a frame annotation (root, code and fields). */
export function describeFrameTree(root: AnnotationNode, direction: 'in' | 'out', name: string | undefined): void {
  const purpose = name ? (direction === 'out' ? CMD_PURPOSE[name as CmdName] : DEV_PURPOSE[name as RespName | PushName]) : undefined;
  root.description ??=
    (direction === 'out' ? 'Companion command, host → device.' : 'Companion frame, device → host (responses < 0x80, pushes ≥ 0x80).') +
    ' One frame per BLE write/notification, or after a 3-byte header on serial. §1';
  const children = root.children ?? [];
  const code = children[0];
  if (code && code.name === 'code') {
    code.description ??= `${name ?? 'Unknown code'}${purpose ? `: ${purpose}` : '.'}`;
  }
  describeNodes(children, `${direction === 'out' ? 'cmd' : 'dev'}.${name ?? '?'}`, FRAME_FIELD_DOCS);
}
